import turtle
print(turtle.position() ) # Get the current position of the turtle


print(turtle.forward(100)) # Move the turtle forward by 100 units
print(turtle.position() ) # Get the current position of the turtle after moving forward
print(turtle.left(90)) # Turn the turtle left by 90 degrees
turtle.forward(50) # Move the turtle forward by 50 units                                
print(turtle.position() ) # Get the current position of the turtle after moving forward
turtle.done()
